#!/usr/bin/env python3
"""Held-out mocks for the Gumroad publish gate — HERMETIC runner (v2, for gate v1.2.2).
Isolation rules (per Cipher's review requirements):
- Scratch state lives in a fresh directory NEXT TO THIS SCRIPT (never /tmp, never the
  live enforcement folder); it is removed on exit.
- The package under test is a fixture ZIP generated by this runner (never a real
  product file).
- The storefront is a fixture HTML page served via file:// — the copied gate's
  STOREFRONT_URL constant is repointed at the fixture (the production code has no
  environment override). The live storefront is never contacted.
- Every case asserts the DENIAL REASON (substring), not only the exit code.
- ALL cases feed ONE results list; the process exit status is 0 only if every case
  passed. Sabotage check: removing any guard from the gate copy must turn the suite
  red (verified during development against the finite-price guard).
Cases: happy path + replay · fail-closed (storefront down, missing package, missing
queue) · concurrent consumption · concurrent AUDIT writes (no chain fork) · tampered
chain · price matrix at gate AND executor (nan/inf/-inf/0/negative, reason-asserted) ·
crash conversion (executor missing package, truncated audit line, string permit price —
each must end as an AUDITED deny, exit 3, no traceback) · permit binding (DENIED-entry
hash reuse, cross-item permit) · action-class normalization (Spend / SPEND / zero-width
bid) · registry strictness (string "false" is not authorized) · HTML-escaped duplicate.
"""
import io, json, os, pathlib, shutil, subprocess, sys, zipfile

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
SCRATCH = SCRIPT_DIR/f".mock-scratch-{os.getpid()}"
HOME = SCRATCH/"home"
ENF_REL = "workspace/operation-mobley/enforcement"
results = []

def check(name, cond, detail=""):
    results.append((name, bool(cond)))
    print(("PASS " if cond else "FAIL ") + name + (f" — {detail}" if detail and not cond else ""))

def fixture_zip(path):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("fixture-a.txt", "fixture content A\n")
        z.writestr("fixture-b.txt", "fixture content B\n")
    path.write_bytes(buf.getvalue())

def build_home(registry=None, storefront="clean"):
    if HOME.exists():
        shutil.rmtree(HOME)
    enf = HOME/ENF_REL
    enf.mkdir(parents=True)
    for f in ["gumroad_publish_gate.py", "gumroad_executor_check.py"]:
        src = (SCRIPT_DIR/f).read_text()
        fixture = (SCRATCH/f"storefront-{storefront}.html").as_uri()
        src = src.replace('STOREFRONT_URL = "https://nickmobley.gumroad.com"',
                          f'STOREFRONT_URL = "{fixture}"')
        (enf/f).write_text(src)
    reg = registry or {
        "TEST-LEGIT-01": {"authorized": True, "price": 19, "queue_complete_marker": "TEST-LEGIT-01 — COMPLETE"},
        "CI-01(a)": {"authorized": True, "price": 24, "queue_complete_marker": "CI-01(a) — COMPLETE"},
    }
    (enf/"gate-registry.json").write_text(json.dumps(reg))
    (HOME/"workspace/operation-mobley/commercial-deliverables-queue.md").write_text(
        "# queue\n\n## CI-01(a) — COMPLETE 2026-10-23 (live listing recorded)\n")
    return enf

def run(script, args, parallel=False):
    env = dict(os.environ)
    env["HOME"] = str(HOME)
    cmd = [sys.executable, str(HOME/ENF_REL/script)] + args
    if parallel:
        return subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env)
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    try:
        return r.returncode, json.loads(r.stdout)
    except Exception:
        return r.returncode, {"raw": r.stdout, "err": r.stderr, "traceback": "Traceback" in r.stderr}

def main():
    SCRATCH.mkdir(exist_ok=True)
    try:
        pkg = SCRATCH/"fixture-pack.zip"
        fixture_zip(pkg)
        (SCRATCH/"storefront-clean.html").write_text("<html><body><h1>Fixture Store</h1><p>Nothing here.</p></body></html>")
        (SCRATCH/"storefront-dup.html").write_text(
            "<html><body><h1>Fixture Store</h1><p>Fish &amp; Chips Career Pack</p></body></html>")
        GATE = "gumroad_publish_gate.py"
        EXE = "gumroad_executor_check.py"
        LEGIT = ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", "--price", "19", "--package", str(pkg)]
        PKG = str(pkg)

        # Happy path: ALLOW -> ACCEPT -> replay DENY
        build_home()
        rc, o = run(GATE, LEGIT); check("happy gate ALLOW", rc == 0 and o.get("decision") == "ALLOW", str(o))
        rc, o = run(EXE, LEGIT); check("happy executor ACCEPT", rc == 0 and o.get("decision") == "ACCEPT", str(o))
        rc, o = run(EXE, LEGIT); check("replay DENY (reason: consumed)", rc == 3 and any("already consumed" in r for r in o.get("reasons", [])), str(o))

        # Duplicate via queue state
        build_home()
        rc, o = run(GATE, ["--item", "CI-01(a)", "--name", "Resume Pack", "--price", "24", "--package", PKG])
        check("duplicate (queue) DENY", rc == 3 and any("queue records this item COMPLETE" in r for r in o.get("reasons", [])), str(o))

        # Fail-closed trio
        build_home(storefront="down")
        rc, o = run(GATE, LEGIT); check("storefront down DENY (reason: fail-closed)", rc == 3 and any("storefront check unavailable" in r for r in o.get("reasons", [])), str(o))
        build_home()
        rc, o = run(GATE, ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", "--price", "19", "--package", str(SCRATCH/"nope.zip")])
        check("missing package DENY (reason)", rc == 3 and any("package file missing" in r for r in o.get("reasons", [])), str(o))
        build_home(); (HOME/"workspace/operation-mobley/commercial-deliverables-queue.md").unlink()
        rc, o = run(GATE, LEGIT); check("queue missing DENY (reason)", rc == 3 and any("queue file unreadable" in r for r in o.get("reasons", [])), str(o))

        # Price matrix — gate (reason-asserted)
        for label, val in [("nan", "nan"), ("inf", "inf"), ("-inf", "-inf"), ("zero", "0"), ("negative", "-5")]:
            build_home()
            rc, o = run(GATE, ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", f"--price={val}", "--package", PKG])
            check(f"gate price {label} DENY (reason)", rc == 3 and any("not a finite positive number" in r for r in o.get("reasons", [])), str(o))
        # Price matrix — executor (valid permit first, then bad price; reason-asserted)
        for label, val in [("nan", "nan"), ("inf", "inf"), ("-inf", "-inf"), ("zero", "0"), ("negative", "-5")]:
            build_home()
            run(GATE, LEGIT)
            rc, o = run(EXE, ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", f"--price={val}", "--package", PKG])
            check(f"executor price {label} DENY (reason)", rc == 3 and any("not a finite positive number" in r for r in o.get("reasons", [])), str(o))

        # Tampered chain
        build_home(); run(GATE, LEGIT)
        audit_p = HOME/ENF_REL/"publish-audit.jsonl"
        lines = audit_p.read_text().strip().splitlines()
        e = json.loads(lines[0]); e["decision"] = "ALLOW-TAMPERED"; lines[0] = json.dumps(e)
        audit_p.write_text("\n".join(lines) + "\n")
        rc, o = run(EXE, LEGIT); check("tampered chain DENY (reason)", rc == 3 and any("chain verification failed" in r for r in o.get("reasons", [])), str(o))

        # Concurrent consumption: exactly one ACCEPT of 6
        build_home(); run(GATE, LEGIT)
        procs = [run(EXE, LEGIT, parallel=True) for _ in range(6)]
        outs = [p.communicate() for p in procs]
        accepts = sum(1 for out, _ in outs if '"decision": "ACCEPT"' in out)
        check("concurrent consumption exactly 1 ACCEPT", accepts == 1, f"accepts={accepts}/6")

        # Concurrent AUDIT writes: 8 parallel gate calls on distinct items -> chain stays valid
        reg = {f"BURST-{i:02d}": {"authorized": True, "price": 10 + i, "queue_complete_marker": f"BURST-{i:02d} — COMPLETE"} for i in range(8)}
        build_home(registry=reg)
        procs = [run(GATE, ["--item", f"BURST-{i:02d}", "--name", f"Burst Product {i}", "--price", str(10 + i), "--package", PKG], parallel=True) for i in range(8)]
        for p in procs: p.communicate()
        import importlib.util
        spec = importlib.util.spec_from_file_location("exe", HOME/ENF_REL/"gumroad_executor_check.py")
        mod = importlib.util.module_from_spec(spec)
        os.environ["HOME"] = str(HOME)
        spec.loader.exec_module(mod)
        entries, ok = mod.load_audit()
        check("concurrent audit writes: log parses", ok, f"entries={len(entries)}")
        check("concurrent audit writes: chain valid (no fork)", ok and mod.verify_chain(entries) and len(entries) == 8,
              f"entries={len(entries)}")

        # Crash conversion B1: executor with missing package -> audited DENY, exit 3, no traceback
        build_home(); run(GATE, LEGIT)
        before = len((HOME/ENF_REL/"publish-audit.jsonl").read_text().strip().splitlines())
        rc, o = run(EXE, ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", "--price", "19", "--package", str(SCRATCH/"gone.zip")])
        after_lines = (HOME/ENF_REL/"publish-audit.jsonl").read_text().strip().splitlines()
        check("executor missing package: audited DENY, no crash",
              rc == 3 and o.get("decision") == "DENY" and len(after_lines) == before + 1 and not o.get("traceback"), str(o))
        # Crash conversion B2: truncated audit line -> audited DENY, exit 3
        build_home(); run(GATE, LEGIT)
        with open(HOME/ENF_REL/"publish-audit.jsonl", "a") as f: f.write('{"ts": "truncated...\n')
        rc, o = run(EXE, LEGIT)
        check("executor truncated audit line: DENY (reason: unparseable, fail-closed)",
              rc == 3 and any("unparseable" in r for r in o.get("reasons", [])), str(o))
        # Crash conversion B3: permit with string price -> audited DENY, no traceback
        build_home(); run(GATE, LEGIT)
        pf = HOME/ENF_REL/"permits"/"TEST-LEGIT-01.json"
        permit = json.loads(pf.read_text()); permit["price"] = "nineteen"; pf.write_text(json.dumps(permit))
        rc, o = run(EXE, LEGIT)
        check("executor string permit price: audited DENY, no crash",
              rc == 3 and o.get("decision") == "DENY" and any("permit price is not a finite number" in r for r in o.get("reasons", [])) and not o.get("traceback"), str(o))

        # Permit binding C1: permit hash repointed at a DENIED entry -> DENY
        build_home()
        run(GATE, ["--item", "TEST-LEGIT-01", "--name", "Synthetic Control Product ZZ", "--price", "99", "--package", PKG])  # DENIED entry
        run(GATE, LEGIT)  # ALLOW entry + permit
        entries = [json.loads(l) for l in (HOME/ENF_REL/"publish-audit.jsonl").read_text().strip().splitlines()]
        denied = next(e for e in entries if e["decision"] == "DENY")
        pf = HOME/ENF_REL/"permits"/"TEST-LEGIT-01.json"
        permit = json.loads(pf.read_text()); permit["audit_hash"] = denied["hash"]; pf.write_text(json.dumps(permit))
        rc, o = run(EXE, LEGIT)
        check("permit bound to DENIED entry: DENY (reason)", rc == 3 and any("not an ALLOW" in r for r in o.get("reasons", [])), str(o))
        # Permit binding C2: permit file for a different item -> DENY
        build_home(); run(GATE, LEGIT)
        pf = HOME/ENF_REL/"permits"/"TEST-LEGIT-01.json"
        permit = json.loads(pf.read_text()); permit["item"] = "OTHER-ITEM"; pf.write_text(json.dumps(permit))
        rc, o = run(EXE, LEGIT)
        check("permit item mismatch vs bound entry: DENY (reason)", rc == 3 and any("item mismatch" in r for r in o.get("reasons", [])), str(o))

        # Action-class normalization D
        for label, cls in [("Spend", "Spend"), ("SPEND", "SPEND"), ("zero-width bid", "bi\u200bd")]:
            build_home()
            rc, o = run(GATE, LEGIT + ["--action-class", cls])
            check(f"action class {label}: DENY (reason: stopped list)", rc == 3 and any("always-stopped" in r for r in o.get("reasons", [])), str(o))

        # Registry strictness E: string "false" must NOT authorize
        build_home(registry={"TEST-LEGIT-01": {"authorized": "false", "price": 19, "queue_complete_marker": "X — COMPLETE"}})
        rc, o = run(GATE, LEGIT)
        check('registry authorized="false" string: DENY (reason)', rc == 3 and any("strict boolean" in r for r in o.get("reasons", [])), str(o))

        # HTML-escaped duplicate F: storefront shows "Fish &amp; Chips..." -> request "Fish & Chips..."
        build_home(storefront="dup")
        rc, o = run(GATE, ["--item", "TEST-LEGIT-01", "--name", "Fish & Chips Career Pack", "--price", "19", "--package", PKG])
        check("HTML-escaped duplicate: DENY (reason)", rc == 3 and any("already live on the storefront" in r for r in o.get("reasons", [])), str(o))

        passed = sum(1 for _, ok in results if ok)
        print(f"\n== FINAL SUMMARY: {passed} / {len(results)} passed")
        return 0 if passed == len(results) else 1
    finally:
        shutil.rmtree(SCRATCH, ignore_errors=True)

if __name__ == "__main__":
    sys.exit(main())
